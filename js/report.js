// Score and Markdown export. Pure.

import { fmtBytes } from './util.js';

/** Counts the summary strip shows. */
export function counts(r) {
  return {
    heavy: r.images.filter((i) => i.flags.some((f) => f === 'heavy' || f === 'oversized' || f === 'png-photo')).length,
    variants: r.images.filter((i) => i.flags.some((f) => f === 'missing-variant' || f === 'no-base' || f === 'same-as-base' || f === 'duplicate')).length,
    unusedAssets: r.assets.unused.length,
    undeclared: r.assets.undeclared.length,
    missing: r.assets.missing.length + r.assets.missingFonts.length,
    unusedFonts: r.assets.unusedFonts.length,
    unusedDeps: r.deps.filter((d) => d.status === 'unused').length,
    testOnly: r.deps.filter((d) => d.status === 'test-only').length,
  };
}

/** 0–100. Each problem costs a few points, capped per kind so one category cannot sink the rest. */
export function score(r) {
  const c = counts(r);
  const cost = (n, each, cap) => Math.min(cap, n * each);
  const penalty =
    cost(c.heavy, 3, 25) +
    cost(c.variants, 1, 8) +
    cost(c.unusedAssets, 1.5, 20) +
    cost(c.undeclared, 0.5, 7) +
    cost(c.missing, 5, 10) +
    cost(c.unusedFonts, 3, 8) +
    cost(c.unusedDeps, 4, 20) +
    cost(c.testOnly, 2, 6);
  return Math.max(0, Math.round(100 - penalty));
}

export const grade = (s) => (s >= 90 ? 'good' : s >= 70 ? 'ok' : 'bad');

/** Markdown for a PR / issue. `size` is the parsed --analyze-size JSON, when loaded. */
export function toMarkdown(r, { href = '', size = null, top = 15 } = {}) {
  const c = counts(r);
  const where = `${r.owner}/${r.repo}${r.dir ? `/${r.dir}` : ''}`;
  const L = [
    `## Assets report — \`${where}\` @ \`${r.ref}\``,
    '',
    `**Score ${r.score}/100** · ${r.images.length} images (${fmtBytes(r.imageTotals.bytes)}) · ${r.scannedAt.slice(0, 10)}`,
    '',
    `heavy images **${c.heavy}** · variant issues **${c.variants}** · unused assets **${c.unusedAssets}** · undeclared **${c.undeclared}** · missing **${c.missing}** · unused fonts **${c.unusedFonts}** · unused deps **${c.unusedDeps}**`,
    '',
  ];
  const flagged = r.images.filter((i) => i.flags.length);
  if (flagged.length) {
    L.push('### Images', '', `Estimated WebP saving: **~${fmtBytes(r.imageTotals.saved)}** (heuristic estimate).`, '',
      '| image | size | px | flags | est. after |', '|---|---:|---|---|---:|');
    for (const i of flagged.slice(0, top)) {
      L.push(`| \`${i.path}\` | ${fmtBytes(i.size)} | ${i.px ? `${i.px.width}×${i.px.height}` : ''} | ${i.flags.join(', ')} | ~${fmtBytes(i.est.after)} |`);
    }
    if (flagged.length > top) L.push(`| …and ${flagged.length - top} more | | | | |`);
    L.push('');
  }
  const list = (title, rows, fmt) => {
    if (!rows.length) return;
    L.push(`### ${title}`, '');
    for (const x of rows.slice(0, 40)) L.push(`- ${fmt(x)}`);
    if (rows.length > 40) L.push(`- …and ${rows.length - 40} more`);
    L.push('');
  };
  list('Unused assets', r.assets.unused, (a) => `\`${a.path}\` (${fmtBytes(a.size)})${a.why === 'dead-constant' ? ' — only in an unused constant' : ''}`);
  list('Not declared in pubspec.yaml', r.assets.undeclared, (a) => `\`${a.path}\` (${fmtBytes(a.size)})`);
  list('Declared but missing', [...r.assets.missing.map((m) => m.path), ...r.assets.missingFonts], (p) => `\`${p}\``);
  list('Unused font families', r.assets.unusedFonts, (f) => `\`${f.family}\` (${fmtBytes(f.bytes)})`);
  list('Unused dependencies', r.deps.filter((d) => d.status === 'unused'), (d) => `\`${d.name}\`${d.section === 'dev' ? ' (dev)' : ''}`);
  list('Only used in tests (move to dev_dependencies)', r.deps.filter((d) => d.status === 'test-only'), (d) => `\`${d.name}\``);
  if (size) {
    L.push(`### ${size.type} size — ${fmtBytes(size.total)}`, '', '| # | contributor | kind | size |', '|---:|---|---|---:|');
    size.contributors.slice(0, 20).forEach((x, n) => L.push(`| ${n + 1} | \`${x.name}\` | ${x.kind} | ${fmtBytes(x.size)}${x.uncompressed ? '*' : ''} |`));
    L.push('', '\\* Dart code sizes are uncompressed snapshot bytes.', '');
  }
  L.push(`_Generated by [Flutter Assets Watch](${href})_`);
  return L.join('\n');
}
